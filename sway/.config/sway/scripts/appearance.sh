#!/usr/bin/env bash
# Appearance menu: GTK theme, dark/light, icons, cursor, font.
# A small rofi stand-in for nwg-look.
#
#   appearance.sh          open the menu
#   appearance.sh --sync   re-apply the saved cursor to sway and rewrite the
#                          GTK ini files (run from sway with exec_always)
#
# gsettings (dconf) is the single source of truth. After each change the
# GTK 3/4 settings.ini files are regenerated from it, for apps that skip
# dconf, and the cursor is pushed to the sway seat so it matches everywhere.
set -euo pipefail

SCHEMA=org.gnome.desktop.interface
DATA_DIRS=("$HOME/.local/share" /usr/local/share /usr/share)

get() { gsettings get "$SCHEMA" "$1" | sed "s/^'//; s/'$//"; }
set_() { gsettings set "$SCHEMA" "$1" "$2"; }

# rofi picker: menu PROMPT CURRENT < options  -> prints the chosen line
menu() {
    local prompt=$1 current=${2:-} opts row
    opts=$(cat)
    row=$(grep -nxF -- "$current" <<<"$opts" | head -1 | cut -d: -f1 || true)
    rofi -dmenu -i -p "$prompt" -no-show-icons \
        ${current:+-mesg "current: $current"} \
        ${row:+-selected-row $((row - 1))} <<<"$opts"
}

# Theme dirs: ~/.themes, */themes, */icons
theme_dirs() {
    local d
    for d in "$HOME/.themes" "${DATA_DIRS[@]/%//themes}"; do if [[ -d $d ]]; then echo "$d"; fi; done
}
icon_dirs() {
    local d
    for d in "$HOME/.icons" "${DATA_DIRS[@]/%//icons}"; do if [[ -d $d ]]; then echo "$d"; fi; done
}

list_gtk_themes() {
    # Adwaita and HighContrast are compiled into GTK 3, so they have no dir
    printf '%s\n' Adwaita Adwaita-dark HighContrast
    local base t
    while read -r base; do
        for t in "$base"/*/; do
            # need real styles; Default/Emacs only ship gtk-keys.css
            if [[ -f ${t}gtk-3.0/gtk.css || -f ${t}gtk-4.0/gtk.css ]]; then basename "$t"; fi
        done
    done < <(theme_dirs)
}

list_icon_themes() {
    local base t
    while read -r base; do
        for t in "$base"/*/; do
            t=${t%/}
            case ${t##*/} in default|hicolor|locolor) continue ;; esac
            # an icon theme lists Directories=; a cursor-only theme does not
            if grep -qs '^Directories=' "$t/index.theme"; then basename "$t"; fi
        done
    done < <(icon_dirs)
}

list_cursor_themes() {
    local base t
    while read -r base; do
        for t in "$base"/*/; do
            t=${t%/}
            [[ ${t##*/} == default ]] && continue
            if [[ -d $t/cursors ]]; then basename "$t"; fi
        done
    done < <(icon_dirs)
}

list_fonts() { fc-list : family | cut -d, -f1 | sort -u; }

theme_has_gtk4() {
    local base
    while read -r base; do [[ -d $base/$1/gtk-4.0 ]] && return 0; done < <(theme_dirs)
    return 1
}

write_ini() {
    local dark=0 theme icons cursor size font
    [[ $(get color-scheme) == prefer-dark ]] && dark=1
    theme=$(get gtk-theme) icons=$(get icon-theme) font=$(get font-name)
    cursor=$(get cursor-theme) size=$(get cursor-size)

    local common="gtk-icon-theme-name=$icons
gtk-cursor-theme-name=$cursor
gtk-cursor-theme-size=$size
gtk-font-name=$font
gtk-application-prefer-dark-theme=$dark"

    mkdir -p "$HOME/.config/gtk-3.0" "$HOME/.config/gtk-4.0"
    printf '# Generated by appearance.sh; edit with $mod+Shift+a\n[Settings]\ngtk-theme-name=%s\n%s\n' \
        "$theme" "$common" >"$HOME/.config/gtk-3.0/settings.ini"
    # GTK 4 falls back to its plain default theme if the named one has no
    # gtk-4.0 dir, so only name it when it does (libadwaita ignores it anyway)
    {
        printf '# Generated by appearance.sh; edit with $mod+Shift+a\n[Settings]\n'
        theme_has_gtk4 "$theme" && printf 'gtk-theme-name=%s\n' "$theme"
        printf '%s\n' "$common"
    } >"$HOME/.config/gtk-4.0/settings.ini"
}

sync_cursor() {
    pgrep -x sway >/dev/null || return 0
    swaymsg -q seat seat0 xcursor_theme "$(get cursor-theme)" "$(get cursor-size)"
}

# Swap a theme to its dark or light twin when one exists (Foo <-> Foo-dark)
twin_theme() {
    local theme=$1 want=$2 base=${1%-dark} candidate
    [[ $want == dark ]] && candidate="$base-dark" || candidate=$base
    list_gtk_themes | grep -qxF -- "$candidate" && echo "$candidate" || echo "$theme"
}

pick_size() { printf '%s\n' "${@:2}" | menu "$1"; }

if [[ ${1:-} == --sync ]]; then
    write_ini
    sync_cursor
    exit 0
fi

# Esc in a submenu goes back to the main menu; Esc on the main menu quits
while true; do
    choice=$(printf '%s\n' "GTK theme" "Dark / Light" "Icons" "Cursor" "Font" | menu "Appearance") || exit 0

    case $choice in
        "GTK theme")
            t=$(list_gtk_themes | sort -u | menu "GTK theme" "$(get gtk-theme)") || continue
            set_ gtk-theme "$t"
            # keep color-scheme consistent with an explicitly dark/light theme
            if [[ $t == *-dark ]]; then set_ color-scheme prefer-dark
            elif list_gtk_themes | grep -qxF -- "$t-dark"; then set_ color-scheme default; fi
            ;;
        "Dark / Light")
            cur=$( [[ $(get color-scheme) == prefer-dark ]] && echo Dark || echo Light )
            m=$(printf '%s\n' Dark Light | menu "Mode" "$cur") || continue
            if [[ $m == Dark ]]; then
                set_ color-scheme prefer-dark
                set_ gtk-theme "$(twin_theme "$(get gtk-theme)" dark)"
            else
                set_ color-scheme default
                set_ gtk-theme "$(twin_theme "$(get gtk-theme)" light)"
            fi
            ;;
        "Icons")
            t=$(list_icon_themes | sort -u | menu "Icons" "$(get icon-theme)") || continue
            set_ icon-theme "$t"
            ;;
        "Cursor")
            t=$(list_cursor_themes | sort -u | menu "Cursor" "$(get cursor-theme)") || continue
            s=$(pick_size "Size" 16 24 32 48 64) || continue
            [[ $s =~ ^[0-9]+$ ]] || continue
            set_ cursor-theme "$t"
            set_ cursor-size "$s"
            sync_cursor
            ;;
        "Font")
            cur=$(get font-name)
            f=$(list_fonts | menu "Font" "${cur% *}") || continue
            s=$(pick_size "Size" 9 10 10.5 11 12 13 14) || continue
            [[ $s =~ ^[0-9]+(\.[0-9]+)?$ ]] || continue
            set_ font-name "$f $s"
            ;;
        *) continue ;;
    esac

    write_ini
    notify-send -a appearance -t 2000 "Appearance" "$choice updated" 2>/dev/null || true
    break
done
